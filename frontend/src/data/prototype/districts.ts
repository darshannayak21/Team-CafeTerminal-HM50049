/**
 * Point-in-polygon ray-casting test
 */
export function isPointInPolygon(point: [number, number], polygon: [number, number][]): boolean {
  const [lat, lng] = point;
  let inside = false;
  const n = polygon.length;
  for (let i = 0, j = n - 1; i < n; j = i++) {
    const [xi, yi] = polygon[i];
    const [xj, yj] = polygon[j];
    const intersect = ((yi > lng) !== (yj > lng)) &&
      (lat < ((xj - xi) * (lng - yi)) / (yj - yi) + xi);
    if (intersect) inside = !inside;
  }
  return inside;
}

/**
 * Robust Taluka Matcher for Ground Reports, Incidents and News:
 * 1. Checks explicit taluka ID or name match.
 * 2. Checks locality keywords (giving priority to Pune City urban areas).
 * 3. Evaluates geographic coordinates against official boundaries & proximity.
 */
export function matchTalukaForIncident(
  inc: {
    taluka?: string | null;
    location?: string;
    location_name?: string;
    description?: string;
    title?: string;
    coordinates?: [number, number] | null;
    latitude?: number | null;
    longitude?: number | null;
  },
  districts: TalukaDistrict[]
): string {
  // 1. Explicit taluka match
  if (inc.taluka) {
    const clean = inc.taluka.toLowerCase().replace('pune-', '').replace(' taluka', '').trim();
    const found = districts.find(
      d => d.id === clean || d.id === `pune-${clean}` || d.name.toLowerCase().includes(clean)
    );
    if (found) return found.id;
  }

  // 2. Keyword match in location / description / title
  const combinedText = `${inc.location || ''} ${inc.location_name || ''} ${inc.description || ''} ${inc.title || ''}`.toLowerCase();
  
  // Prioritize Pune City keywords so any Pune urban reports don't spill into rural Haveli
  for (const kw of TALUKA_LOCALITY_KEYWORDS['pune-city']) {
    if (combinedText.includes(kw)) {
      const puneDistrict = districts.find(d => d.id === 'pune-city');
      if (puneDistrict) return puneDistrict.id;
    }
  }

  // Check Haveli keywords only for genuine Haveli localities
  if (combinedText.includes('haveli taluka') || combinedText.includes('haveli sub-division')) {
    const haveliDistrict = districts.find(d => d.id === 'haveli');
    if (haveliDistrict) return haveliDistrict.id;
  }

  for (const kw of TALUKA_LOCALITY_KEYWORDS['haveli']) {
    if (combinedText.includes(kw)) {
      const haveliDistrict = districts.find(d => d.id === 'haveli');
      if (haveliDistrict) return haveliDistrict.id;
    }
  }

  // Check all other talukas
  for (const [talukaId, keywords] of Object.entries(TALUKA_LOCALITY_KEYWORDS)) {
    if (talukaId === 'pune-city' || talukaId === 'haveli') continue;
    for (const kw of keywords) {
      if (combinedText.includes(kw)) {
        const found = districts.find(d => d.id === talukaId);
        if (found) return found.id;
      }
    }
  }

  // Direct district name match
  for (const d of districts) {
    const cleanName = d.name
      .toLowerCase()
      .replace(' catchment', '')
      .replace(' mountain valley', '')
      .replace(' taluka', '')
      .replace(' metro', '');
    if (combinedText.includes(d.id.toLowerCase()) || combinedText.includes(cleanName)) {
      return d.id;
    }
  }

  // 3. Spatial Coordinate Resolution
  const coords: [number, number] | null = inc.coordinates
    ? inc.coordinates
    : typeof inc.latitude === 'number' && typeof inc.longitude === 'number'
    ? [inc.latitude, inc.longitude]
    : null;

  if (coords && coords[0] && coords[1]) {
    // If coordinate is in Pune urban core (~14km around 18.53, 73.88), assign to pune-city
    const puneCity = districts.find(d => d.id === 'pune-city');
    if (puneCity?.centerCoordinates) {
      const distToPune = Math.hypot(puneCity.centerCoordinates[0] - coords[0], puneCity.centerCoordinates[1] - coords[1]);
      if (distToPune < 0.12) {
        return 'pune-city';
      }
    }

    // Check exact point in polygon for other districts
    for (const d of districts) {
      if (d.id === 'haveli') continue; // Don't let Haveli's wrap-around border capture other talukas
      if (d.polygonCoordinates && d.polygonCoordinates.length > 2) {
        if (isPointInPolygon(coords, d.polygonCoordinates)) {
          return d.id;
        }
      }
    }

    // Check Haveli polygon as fallback
    const haveliDist = districts.find(d => d.id === 'haveli');
    if (haveliDist?.polygonCoordinates && isPointInPolygon(coords, haveliDist.polygonCoordinates)) {
      return 'haveli';
    }

    // Nearest center distance
    let nearestTaluka = districts[0]?.id || 'pune-city';
    let minDistance = Infinity;
    for (const d of districts) {
      if (d.centerCoordinates) {
        const dist = Math.hypot(d.centerCoordinates[0] - coords[0], d.centerCoordinates[1] - coords[1]);
        if (dist < minDistance) {
          minDistance = dist;
          nearestTaluka = d.id;
        }
      }
    }
    return nearestTaluka;
  }

  // Fallback default
  return districts[0]?.id || 'pune-city';
}

